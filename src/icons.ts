const escapeAttribute = (value: string): string =>
  value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

/** Always aria-hidden, so an icon-only control needs its own aria-label; an unknown name throws. */
export function renderIcon(name: string, className = ''): string {
  const paths = ICON_PATHS[name];
  if (!paths) throw new Error(`Unknown icon "${name}"`);
  const cls = className ? ` class="${escapeAttribute(className)}"` : '';
  const body = paths.map((d) => `<path d="${d}"/>`).join('');
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none"' +
    ' stroke="currentColor" stroke-width="1.75" stroke-linecap="round"' +
    ` stroke-linejoin="round" aria-hidden="true" focusable="false"${cls}>` +
    `${body}</svg>`
  );
}
